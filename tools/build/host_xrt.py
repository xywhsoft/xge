"""Generate typed XRT host imports from the pinned, authoritative C header.

No forwarding functions or XRT implementation are emitted. Unsupported API
declarators fail closed; ordinary C compile/link checks remain authoritative.
"""
from pathlib import Path
import hashlib
import json
import re


def write_changed(path, data):
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def mask_c(text):
    """Keep offsets/newlines, hide comments and quoted tokens from the parser."""
    pattern = r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\''
    return re.sub(pattern, lambda m: re.sub(r'[^\n]', ' ', m[0]), text, flags=re.S)


def generate(header, output):
    header, output = Path(header), Path(output)
    raw = header.read_bytes()
    text = raw.decode('utf-8-sig').replace('\r\n', '\n')
    canonical_digest = hashlib.sha256(text.encode()).hexdigest()
    marker = '#if defined(XRT_IMPLEMENTATION) && !defined(XRT_IMPLEMENTATION_ONCE)'
    if text.count(marker) != 1:
        raise ValueError('XRT declaration/implementation boundary changed')
    text = text.split(marker)[0]
    masked = mask_c(text)
    changes, names = [], []
    for match in re.finditer(r'\bXRT_API\b', masked):
        line = masked[masked.rfind('\n', 0, match.start())+1:match.start()]
        if line.lstrip().startswith('#'):
            continue
        end = masked.find(';', match.end())
        if end < 0 or '{' in masked[match.end():end]:
            raise ValueError('Unsupported XRT API declaration at '+str(match.start()))
        declaration = masked[match.end():end]
        first = declaration.find('(')
        function = re.search(r'\b((?:__)?xrt[A-Z]\w*)\s*$', declaration[:first]) if first >= 0 else None
        if not function or declaration.count('(') != declaration.count(')'):
            raise ValueError('Unsupported XRT API declarator: '+declaration[:160])
        name = function[1]
        relative = function.start(1)
        prefix = text[match.end():match.end()+relative]
        suffix = text[match.end()+relative+len(name):end]
        replacement = (f'typedef{prefix}XgeHostXrtType_{name}{suffix};\n'
            f'extern XGE_HOST_XRT_IMPORT_PRIVATE XgeHostXrtType_{name}* XgeHostXrtSlot_{name};\n'
            f'#define {name} (*XgeHostXrtSlot_{name})')
        changes.append((match.start(), end+1, replacement))
        names.append(name)
    if not names:
        raise ValueError('No XRT API declarations found')
    # Alias definitions would otherwise silently override a typed import.
    macro_names = set(re.findall(r'^\s*#\s*define\s+(\w+)', masked, re.M))
    wrapped = macro_names.intersection(names)
    debug_wrappers = {'xrtMalloc', 'xrtCalloc', 'xrtRealloc', 'xrtFree', 'xrtMemDup'}
    if wrapped.difference(debug_wrappers):
        raise ValueError('XRT function macro requires an explicit import rule: '+str(wrapped))
    for begin, end, replacement in reversed(changes):
        text = text[:begin]+replacement+text[end:]
    # Preserve the authoritative file/line debug wrappers in their original
    # conditional scope. Their At targets are typed imports too. An attempt to
    # take the wrapped raw function address fails at compile time rather than
    # importing a hidden second runtime.
    for name in sorted(wrapped):
        pattern = rf'^(\s*#\s*define\s+{name}\([^\n]*{name}At[^\n]*)$'
        text, count = re.subn(pattern, lambda m: f'#undef {name}\n'+m[1], text, flags=re.M)
        if count != 1:
            raise ValueError('XRT debug wrapper changed: '+name)
    digest = canonical_digest
    preamble = ('/* Generated by tools/build/host_xrt.py; do not edit. */\n'
        '#ifdef XRT_IMPLEMENTATION\n#error "Hosted XGE must not compile XRT_IMPLEMENTATION"\n#endif\n'
        '#ifdef XRT_SINGLE_HEADER_H\n#error "Host imports must precede ordinary XRT declarations"\n#endif\n'
        '#if defined(_WIN32)\n#define XGE_HOST_XRT_IMPORT_PRIVATE\n#else\n'
        '#define XGE_HOST_XRT_IMPORT_PRIVATE __attribute__((visibility("hidden")))\n#endif\n')
    output.mkdir(parents=True, exist_ok=True)
    write_changed(output/'xge_host_xrt_imports.h', (preamble+text).encode())
    write_changed(output/'xge_host_xrt_fingerprint.h', (
        '#ifndef XGE_HOST_XRT_FINGERPRINT_H\n#define XGE_HOST_XRT_FINGERPRINT_H\n'
        f'#define XGE_HOST_XRT_HEADER_SHA256 "{digest}"\n#endif\n').encode())
    # Compile this same contract against the host's own pinned declarations.
    # Do not copy the consumer's observed values into a host descriptor.
    write_changed(output/'xge_host_xrt_contract.h', ('''/* Generated; include after matching XRT declarations. */
#ifndef XGE_HOST_XRT_CONTRACT_H
#define XGE_HOST_XRT_CONTRACT_H
#include "xge_host_xrt.h"
#include "xge_host_xrt_fingerprint.h"
#include <wchar.h>
#if defined(_WIN64) && defined(__x86_64__)
#define XGE_HOST_XRT_TARGET 1u
#elif defined(__linux__) && defined(__x86_64__)
#define XGE_HOST_XRT_TARGET 2u
#else
#error "XGE hosted XRT has not been validated for this target ABI"
#endif
struct XgeHostXrtScalarAlignment { char c; void* p; double d; };
struct XgeHostXrtViewAlignment { char c; xstrview v; };
#define XGE_HOST_XRT_DATA_MODEL ((uint64_t)XGE_HOST_XRT_TARGET | \\
 ((uint64_t)sizeof(void*)<<8) | ((uint64_t)sizeof(size_t)<<12) | \\
 ((uint64_t)sizeof(long)<<16) | ((uint64_t)sizeof(wchar_t)<<20) | \\
 ((uint64_t)sizeof(double)<<24) | ((uint64_t)sizeof(int)<<28) | \\
 ((uint64_t)offsetof(struct XgeHostXrtScalarAlignment,p)<<32) | \\
 ((uint64_t)offsetof(struct XgeHostXrtScalarAlignment,d)<<40))
#define XGE_HOST_XRT_CORE_LAYOUT ((uint64_t)sizeof(xstrview) | \\
 ((uint64_t)offsetof(struct XgeHostXrtViewAlignment,v)<<16) | \\
 ((uint64_t)sizeof(xrtresourcelimits)<<32))
#define XGE_HOST_XRT_LOCAL_CONTRACT_INIT {sizeof(xge_host_xrt_contract_t), 1u, \\
 XGE_HOST_XRT_DATA_MODEL, XGE_HOST_XRT_CORE_LAYOUT, XGE_HOST_XRT_HEADER_SHA256}
#endif
''').encode())
    metadata = dict(schema=1, headerSha256=digest, sourceSha256=hashlib.sha256(raw).hexdigest(),
        names=sorted(set(names)), declarations=len(names))
    write_changed(output/'xge_host_xrt_imports.json', (json.dumps(metadata, indent=2)+'\n').encode())
    return metadata


def required_symbols(nm_output, metadata):
    required = set(re.findall(r'\bXgeHostXrtSlot_((?:__)?xrt\w+)\b', nm_output))
    unknown = required.difference(metadata['names'])
    if unknown:
        raise ValueError('Unknown XRT host imports: '+str(unknown))
    # Plain unresolved names reveal an inline helper or other reference that
    # escaped transformation. Never paper over it with a second runtime/thunk.
    raw = set(re.findall(r'\b(?:__imp_)?((?:__)?xrt[A-Z]\w+)\s*$', nm_output, re.M))
    if raw:
        raise ValueError('Unmapped direct XRT imports: '+str(sorted(raw)))
    return sorted(required | {'xrtVersion'})


def write_slots(output, names):
    output = Path(output)
    lines = ['/* Generated required typed slots; no runtime implementation. */']
    for name in names:
        if not re.fullmatch(r'(?:__)?xrt[A-Z]\w*', name):
            raise ValueError('Invalid symbol name')
        lines.append(f'XGE_HOST_XRT_SLOT({name})')
    write_changed(output/'xge_host_xrt_slots.inc', ('\n'.join(lines)+'\n').encode())


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    generate(args.header, args.output)
